function inventory = create_stage2b_architecture_diagrams(cfgKao, cfgCerebellum)
%CREATE_STAGE2B_ARCHITECTURE_DIAGRAMS Matched publication-quality schematics.

    configurations = {cfgKao, cfgCerebellum};
    stageNames = ["Stage 2B-Kao", "Stage 2B-Cerebellum"];
    basenames = ["stage2b_kao_architecture", ...
        "stage2b_cerebellum_architecture"];
    rows = cell(2, 6);
    for stage = 1:2
        root = fullfile(configurations{stage}.resultsRoot, 'architecture');
        if ~isfolder(root)
            mkdir(root);
        end
        handle = architecture_figure(stage);
        pngPath = fullfile(root, [char(basenames(stage)), '.png']);
        svgPath = fullfile(root, [char(basenames(stage)), '.svg']);
        exportgraphics(handle, pngPath, 'Resolution', 300, ...
            'BackgroundColor', 'white');
        exportgraphics(handle, svgPath, 'ContentType', 'vector', ...
            'BackgroundColor', 'white');
        close(handle);
        svgText = fileread(svgPath);
        isVector = contains(svgText, '<svg') && ...
            (contains(svgText, '<path') || contains(svgText, '<polygon')) && ...
            ~contains(svgText, '<image');
        assert(isVector, 'Architecture SVG is not genuinely vector/editable.');
        info = imfinfo(pngPath);
        assert(info.Width >= 2400 && info.Height >= 800);
        rows(stage, :) = {stageNames(stage), basenames(stage), ...
            string(pngPath), string(svgPath), info.Width, info.Height};
    end
    inventory = cell2table(rows, 'VariableNames', ...
        {'Stage','Basename','PNG','SVG','PngWidth','PngHeight'});
end

function handle = architecture_figure(stage)
    handle = figure('Visible', 'off', 'Color', 'white', ...
        'Units', 'pixels', 'Position', [40, 80, 2200, 780], ...
        'Name', 'Stage 2B architecture');
    axes(handle, 'Position', [0, 0, 1, 1], 'Visible', 'off', ...
        'XLim', [0, 1], 'YLim', [0, 1]);
    palette.target = [0.91, 0.95, 0.99];
    palette.controller = [0.98, 0.91, 0.80];
    palette.m1 = [0.87, 0.94, 0.88];
    palette.motor = [0.91, 0.94, 0.99];
    palette.neutral = [0.96, 0.96, 0.96];
    palette.timing = [1.00, 0.98, 0.88];
    if stage == 1
        titleText = ['Stage 2B-Kao: unrestricted 200-D theoretical ' ...
            'preparatory feedback'];
    else
        titleText = ['Stage 2B-Cerebellum: normative 13-D cortical ' ...
            'actuator capacity bound'];
    end
    annotation(handle, 'textbox', [0.025, 0.925, 0.95, 0.055], ...
        'String', titleText, 'EdgeColor', 'none', ...
        'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle', ...
        'FontSize', 20, 'FontWeight', 'bold', 'Interpreter', 'tex');
    annotation(handle, 'textbox', [0.22, 0.845, 0.62, 0.055], ...
        'String', ['PREP: tonic + feedback ON    |    GO: tonic + feedback ' ...
        'OFF; common movement-initiation input ON'], ...
        'EdgeColor', [0.60, 0.55, 0.30], 'BackgroundColor', palette.timing, ...
        'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle', ...
        'FontSize', 12, 'FontWeight', 'bold');

    add_block(handle, [0.025, 0.48, 0.080, 0.11], 'Target q', palette.target, 14);
    add_block(handle, [0.140, 0.68, 0.135, 0.11], ...
        {'Analytic tonic'; 'u_q^*'}, palette.target, 14);
    add_block(handle, [0.140, 0.38, 0.135, 0.11], ...
        {'Desired M1 rate'; 'r_q^*'}, palette.target, 14);
    add_block(handle, [0.310, 0.38, 0.115, 0.11], ...
        {'Rate error'; 'r(t) - r_q^*'}, palette.neutral, 14);
    add_block(handle, [0.795, 0.605, 0.050, 0.075], ...
        'sum', palette.neutral, 13);
    add_block(handle, [0.875, 0.55, 0.105, 0.17], ...
        {'Frozen M1'; '200 units'; '160E + 40I'}, palette.m1, 14);
    add_block(handle, [0.590, 0.075, 0.155, 0.105], ...
        {'Frozen rank-2'; 'motor readout'}, palette.motor, 13);
    add_block(handle, [0.825, 0.075, 0.125, 0.105], ...
        'Two-link arm', palette.motor, 13);
    add_block(handle, [0.555, 0.735, 0.180, 0.070], ...
        'Common GO / movement input', palette.motor, 12);

    if stage == 1
        add_block(handle, [0.465, 0.38, 0.150, 0.11], ...
            {'Full-state LQR'; 'K (200 \times 200)'}, ...
            palette.controller, 14);
        add_block(handle, [0.655, 0.38, 0.130, 0.11], ...
            {'Unrestricted'; '200-D feedback'}, palette.controller, 14);
        add_arrow(handle, [0.425, 0.465], [0.435, 0.435]);
        add_arrow(handle, [0.615, 0.655], [0.435, 0.435]);
        add_arrow(handle, [0.785, 0.815], [0.435, 0.605]);
    else
        add_block(handle, [0.445, 0.38, 0.120, 0.11], ...
            {'LQR'; 'K (13 \times 200)'}, palette.controller, 13);
        add_block(handle, [0.590, 0.38, 0.085, 0.11], ...
            {'13-D'; 'z(t)'}, palette.controller, 13);
        add_block(handle, [0.700, 0.345, 0.145, 0.18], ...
            {'Fixed B_{CB}'; '(200 \times 13)'; ...
            'top-13 Q basis'}, palette.controller, 13);
        add_arrow(handle, [0.425, 0.445], [0.435, 0.435]);
        add_arrow(handle, [0.565, 0.590], [0.435, 0.435]);
        add_arrow(handle, [0.675, 0.700], [0.435, 0.435]);
        add_arrow(handle, [0.845, 0.815], [0.435, 0.605]);
        annotation(handle, 'textbox', [0.405, 0.275, 0.44, 0.045], ...
            'String', ['Fixed movement-potent cortical actuator basis; ' ...
            'not an anatomical cerebellar/thalamic population'], ...
            'EdgeColor', 'none', 'HorizontalAlignment', 'center', ...
            'FontSize', 11, 'FontAngle', 'italic', ...
            'Color', [0.30, 0.30, 0.30]);
    end

    add_arrow(handle, [0.105, 0.140], [0.535, 0.735]);
    add_arrow(handle, [0.105, 0.140], [0.535, 0.435]);
    add_arrow(handle, [0.275, 0.310], [0.435, 0.435]);
    add_arrow(handle, [0.275, 0.795], [0.735, 0.642]);
    add_arrow(handle, [0.735, 0.795], [0.770, 0.642]);
    add_arrow(handle, [0.845, 0.875], [0.642, 0.635]);
    add_arrow(handle, [0.925, 0.745], [0.550, 0.180]);
    add_arrow(handle, [0.745, 0.825], [0.127, 0.127]);

    add_line(handle, [0.875, 0.845], [0.565, 0.285]);
    add_line(handle, [0.845, 0.368], [0.285, 0.285]);
    add_arrow(handle, [0.368, 0.368], [0.285, 0.380]);
    annotation(handle, 'textbox', [0.480, 0.235, 0.260, 0.040], ...
        'String', 'Current frozen-M1 rate r(t)', 'EdgeColor', 'none', ...
        'HorizontalAlignment', 'center', 'FontSize', 11, ...
        'Color', [0.25, 0.25, 0.25], 'Interpreter', 'tex');
end

function add_block(handle, position, label, color, fontSize)
    annotation(handle, 'textbox', position, 'String', label, ...
        'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle', ...
        'FontSize', fontSize, 'FontWeight', 'bold', 'LineWidth', 1.1, ...
        'EdgeColor', [0.18, 0.18, 0.18], 'BackgroundColor', color, ...
        'Interpreter', 'tex', 'Margin', 5);
end

function add_arrow(handle, x, y)
    annotation(handle, 'arrow', x, y, 'Color', [0.18, 0.18, 0.18], ...
        'LineWidth', 1.35, 'HeadLength', 7, 'HeadWidth', 7);
end

function add_line(handle, x, y)
    annotation(handle, 'line', x, y, 'Color', [0.28, 0.28, 0.28], ...
        'LineWidth', 1.15);
end

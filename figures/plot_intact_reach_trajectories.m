function figureFiles = plot_intact_reach_trajectories( ...
        diagnostics, task, params)
    figureHandle = figure('Color', 'w', 'Visible', params.plot.visible);
    axesHandle = axes(figureHandle);
    hold(axesHandle, 'on');

    for targetIndex = 1:params.task.numTargets
        color = params.plot.targetColors(targetIndex, :);
        desired = 100 * squeeze( ...
            diagnostics.meanDesiredPosition(:, targetIndex, :));
        generated = 100 * squeeze( ...
            diagnostics.meanPosition(:, targetIndex, :));
        plot(axesHandle, desired(1, :), desired(2, :), '--', ...
            'Color', color, 'LineWidth', params.plot.referenceLineWidth, ...
            'HandleVisibility', 'off');
        plot(axesHandle, generated(1, :), generated(2, :), '-', ...
            'Color', color, 'LineWidth', params.plot.lineWidth, ...
            'HandleVisibility', 'off');
        plot(axesHandle, 100 * task.targetPositions(1, targetIndex), ...
            100 * task.targetPositions(2, targetIndex), 'o', ...
            'Color', color, 'MarkerFaceColor', color, ...
            'HandleVisibility', 'off');
    end
    plot(axesHandle, 100 * task.centerPosition(1), ...
        100 * task.centerPosition(2), 'ko', 'MarkerFaceColor', 'k', ...
        'HandleVisibility', 'off');
    desiredHandle = plot(axesHandle, nan, nan, 'k--', ...
        'LineWidth', params.plot.referenceLineWidth);
    generatedHandle = plot(axesHandle, nan, nan, 'k-', ...
        'LineWidth', params.plot.lineWidth);
    legendHandle = legend(axesHandle, ...
        [desiredHandle, generatedHandle], ...
        {'Desired minimum jerk', 'Generated mean'}, ...
        'Location', 'best');
    set(legendHandle, 'Box', 'off');
    xlabel(axesHandle, 'Horizontal hand position (cm)');
    ylabel(axesHandle, 'Vertical hand position (cm)');
    title(axesHandle, 'Intact V1 endpoint trajectories');
    axis(axesHandle, 'equal');
    apply_plot_style(axesHandle, params);
    figureFiles = save_figure_bundle(figureHandle, fullfile( ...
        params.files.figureRoot, 'behavior', ...
        'intact_reach_trajectories'), params);
end

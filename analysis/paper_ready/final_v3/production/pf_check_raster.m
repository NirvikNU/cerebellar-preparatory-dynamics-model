function receipt=pf_check_raster(name,reference,actual)
    % Exact raster check with ten fixed ED5b edge palettes.
    rule=struct('panel','ED5b','dimensionsWH',[1750 1167], ...
        'xyZeroBased',[1228 367;1228 369;1092 647;1093 647;1093 649;1095 649;1093 650; ...
            1228 359;1228 361;1229 361], ...
        'referenceRGBA',uint8([165 102 51 255;185 124 76 255;58 120 156 255;112 150 172 255; ...
            86 150 187 255;189 201 208 255;108 169 205 255; ...
            142 100 67 255;184 161 143 255;124 64 16 255]), ...
        'alternateRGBA',uint8([176 107 51 255;183 123 76 255;57 120 156 255;112 151 174 255; ...
            85 149 186 255;188 197 203 255;106 165 199 255; ...
            142 99 66 255;174 151 133 255;124 63 15 255]), ...
        'matlab','25.2.0.3042426 (R2025b) Update 1','screenPPI',96,'resolutionDPI',160, ...
        'renderer','vector','maximumChangedPixels',10);
    if nargin==0,receipt=rule;return;end
    assert(isa(reference,'uint8')&&isa(actual,'uint8')&&size(reference,3)==4&&size(actual,3)==4);
    assert(isequal(size(reference),size(actual)),'Publication:RasterDimensions','Image dimensions differ %s',name);
    changed=any(reference~=actual,3);count=nnz(changed);
    receipt=struct('accepted',true,'exact',count==0,'approvedPixels',0);
    if count==0,return;end
    assert(strcmp(name,rule.panel)&&isequal(size(actual),[1167 1750 4]), ...
        'Publication:RasterMismatch','Unapproved raster pixels %s',name);
    assert(strcmp(version,rule.matlab)&&get(groot,'ScreenPixelsPerInch')==rule.screenPPI, ...
        'Publication:RasterEnvironment','ED5b exception requires its measured environment.');
    for k=1:size(rule.xyZeroBased,1)
        x=rule.xyZeroBased(k,1)+1;y=rule.xyZeroBased(k,2)+1;changed(y,x)=false;
        palette=[rule.referenceRGBA(k,:);rule.alternateRGBA(k,:)];
        a=reshape(reference(y,x,:),1,4);b=reshape(actual(y,x,:),1,4);
        assert(ismember(a,palette,'rows')&&ismember(b,palette,'rows'), ...
            'Publication:RasterColour','Unapproved complete RGBA value %s',name);
    end
    assert(count<=rule.maximumChangedPixels&&~any(changed,'all'), ...
        'Publication:RasterSite','Unapproved changed pixel %s',name);
    receipt.approvedPixels=count;
end

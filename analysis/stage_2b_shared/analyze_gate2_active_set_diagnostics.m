function validation = validate_figures(files)
    validation = table();
    names = fieldnames(files);
    for index = 1:numel(names)
        item = files.(names{index});
        reopened = openfig(item.fig, 'invisible');
        assert(isgraphics(reopened));
        close(reopened);
        image = imread(item.png);
        passed = size(image, 1) >= 800 && size(image, 2) >= 1200;
        assert(passed);
        validation = [validation; table(string(names{index}), ... %#ok<AGROW>
            string(item.png), string(item.fig), size(image, 2), ...
            size(image, 1), passed, 'VariableNames', {'Figure','PNG','FIG', ...
            'Width','Height','Passed'})];
    end
end

function [matched, check] = compare_manifests(before, after)
    before = sortrows(before, 'relative_path');
    after = sortrows(after, 'relative_path');
    samePaths = isequal(before.relative_path, after.relative_path);
    if samePaths
        same = before.sha256 == after.sha256 & before.bytes == after.bytes;
    else
        same = false(max(height(before), height(after)), 1);
    end
    matched = samePaths && all(same);
    check = table("All frozen canonical scopes", height(before), ...
        height(after), matched, 'VariableNames', {'Scope','FilesBefore', ...
        'FilesAfter','AllHashesMatch'});
end


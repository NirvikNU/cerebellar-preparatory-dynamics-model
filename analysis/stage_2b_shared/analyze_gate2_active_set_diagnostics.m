function report = analyze_gate2_active_set_diagnostics(projectRoot)
    %#ok<*AGROW,*UDIM>
    cfg = stage_2b_kao_config(projectRoot);
    diagnostic = diagnostic_config(cfg);
    make_directories(diagnostic);
    frozenBefore = capture_frozen_manifest(projectRoot, diagnostic.frozenRoots);
    writetable(frozenBefore, fullfile(diagnostic.auditRoot, ...
        'frozen_canonical_manifest_before.csv'));
    savedKao = load(fullfile(cfg.resultsRoot, ...
        'stage2b_kao_gate3_complete.mat'), 'complete');
    acceptedMovement = savedKao.complete.results.movement;
    assert(height(acceptedMovement) == 2 * cfg.ensemble.count * 8 * 51);
    stage1Target = table();
    stage1Overlap = table();
    stage1ActiveCurve = table();
    frozenMetrics = table();
    frozenCurves = table();
    preparationTarget = table();
    representative = struct();
    validationRows = table();
    startTime = tic;
    for network = 1:cfg.ensemble.count
        modelPath = fullfile(cfg.ensemble.stage1Root, ...
            sprintf('network_%02d.mat', network));
        loaded = load(modelPath, 'model');
        model = loaded.model;
        stage2aPath = fullfile(cfg.ensemble.stage2aRoot, ...
            sprintf('network_%02d_stage2a.mat', network));
        stage2aSaved = load(stage2aPath, 'networkResult');
        tonic = model.xstar - model.W * max(model.xstar, 0) - model.h;
        assert(max(abs(tonic - stage2aSaved.networkResult.tonicInput), ...
            [], 'all') < 1e-12);
        kao = derive_stage2b_kao_controller(model, cfg);
        [targetRows, overlapRows, curveRows, frozenRows, curveMismatch, ...
            representativeMovement, stage1Validation] = ...
            analyze_stage1_network(model, network);
        stage1Target = [stage1Target; targetRows];
        stage1Overlap = [stage1Overlap; overlapRows];
        stage1ActiveCurve = [stage1ActiveCurve; curveRows];
        frozenMetrics = [frozenMetrics; frozenRows];
        frozenCurves = [frozenCurves; curveMismatch];
        [preparationRows, preparationValidation] = ...
            analyze_preparation_network(cfg, model, tonic, kao, network, ...
            acceptedMovement);
        preparationTarget = [preparationTarget; preparationRows];
        validationRows = [validationRows; stage1Validation; ...
            preparationValidation];
        if network == cfg.ensemble.representativeIndex
            representative.movement = representativeMovement;
        end
        fprintf('Completed Gate-2 diagnostic network %d/%d.\n', ...
            network, cfg.ensemble.count);
    end
    [stage1Network, activeCurveNetwork, frozenNetwork, frozenCurveNetwork] = ...
        summarize_stage1(stage1Target, stage1Overlap, stage1ActiveCurve, ...
        frozenMetrics, frozenCurves, diagnostic);
    [preparationNetwork, preparationEnsemble, timing] = ...
        summarize_preparation(preparationTarget, diagnostic);
    results = struct('stage1Target', stage1Target, ...
        'stage1Overlap', stage1Overlap, ...
        'stage1ActiveCurve', stage1ActiveCurve, ...
        'stage1Network', stage1Network, ...
        'stage1ActiveCurveNetwork', activeCurveNetwork, ...
        'frozenRegimeTarget', frozenMetrics, ...
        'frozenRegimeCurve', frozenCurves, ...
        'frozenRegimeNetwork', frozenNetwork, ...
        'frozenRegimeCurveNetwork', frozenCurveNetwork, ...
        'preparationTarget', preparationTarget, ...
        'preparationNetwork', preparationNetwork, ...
        'preparationEnsemble', preparationEnsemble, ...
        'preparationTiming', timing, 'validation', validationRows);
    save(fullfile(diagnostic.resultsRoot, ...
        'gate2_active_set_diagnostics_complete.mat'), 'results', ...
        'representative', 'diagnostic', '-v7.3');
    write_result_tables(diagnostic.tableRoot, results);
    figureFiles = create_gate2_active_set_figures(cfg, diagnostic, ...
        results, representative);
    figureValidation = validate_figures(figureFiles);
    frozenAfter = capture_frozen_manifest(projectRoot, diagnostic.frozenRoots);
    writetable(frozenAfter, fullfile(diagnostic.auditRoot, ...
        'frozen_canonical_manifest_after.csv'));
    [frozenMatched, frozenCheck] = compare_manifests(frozenBefore, frozenAfter);
    assert(frozenMatched, 'A frozen canonical artifact changed.');
    writetable(frozenCheck, fullfile(diagnostic.auditRoot, ...
        'frozen_canonical_verification.csv'));
    assert(all(validationRows.Passed));
    summary = build_summary(results, figureFiles, figureValidation, ...
        frozenMatched, toc(startTime), diagnostic);
    write_json(fullfile(diagnostic.resultsRoot, ...
        'gate2_active_set_diagnostics_summary.json'), summary);
    artifactManifest = hash_tree(projectRoot, [
        "results/stage_1/diagnostics/active_set_gate2";
        "results/stage_2a/diagnostics/active_set_gate2";
        "results/stage_2b_kao/diagnostics/active_set_gate2";
        "plots/stage_1/diagnostics/active_set_gate2";
        "plots/stage_2b_kao/diagnostics/active_set_gate2"]);
    writetable(artifactManifest, fullfile(diagnostic.auditRoot, ...
        'diagnostic_artifact_manifest_sha256.csv'));
    codeManifest = hash_tree(projectRoot, [
        "workflows/diagnostics/stage_2b_kao/run_gate2_active_set_diagnostics.m";
        "analysis/stage_2b_shared/analyze_gate2_active_set_diagnostics.m";
        "figures/stage_2b_shared/create_gate2_active_set_figures.m"]);
    writetable(codeManifest, fullfile(diagnostic.auditRoot, ...
        'diagnostic_code_manifest_sha256.csv'));
    report = struct('summary', summary, 'figureFiles', figureFiles, ...
        'figureValidation', figureValidation, ...
        'frozenVerification', frozenCheck);
end


function output = timing_to_struct(timing)
    controllers = unique(timing.Controller, 'stable');
    output = repmat(struct(), numel(controllers), 1);
    for index = 1:numel(controllers)
        rows = timing.Controller == controllers(index);
        output(index).controller = char(controllers(index));
        output(index).activeMismatchAtMost1PercentMedianMs = ...
            1000 * median(timing.FirstActiveMismatchAtMost1PercentS(rows), ...
            'omitmissing');
        output(index).zeroMedianActiveMismatchMedianMs = ...
            1000 * median(timing.FirstZeroMedianActiveMismatchS(rows), ...
            'omitmissing');
        output(index).t95ProspectiveMedianMs = ...
            1000 * median(timing.FirstT95ProspectiveS(rows), 'omitmissing');
        output(index).endpointAtMost2mmMedianMs = ...
            1000 * median(timing.FirstMedianEndpointAtMost2mmS(rows), ...
            'omitmissing');
        output(index).networksReachingActive1Percent = sum(~isnan( ...
            timing.FirstActiveMismatchAtMost1PercentS(rows)));
        output(index).networksReachingT95 = sum(~isnan( ...
            timing.FirstT95ProspectiveS(rows)));
        output(index).networksReachingEndpoint2mm = sum(~isnan( ...
            timing.FirstMedianEndpointAtMost2mmS(rows)));
    end
end

function value = normalized_rmse(actual, reference)
    numerator = sqrt(mean((actual - reference) .^ 2, 'all'));
    denominator = max(max(reference, [], 'all') - ...
        min(reference, [], 'all'), eps);
    value = numerator / denominator;
end

function write_json(path, value)
    text = jsonencode(value, PrettyPrint=true);
    file = fopen(path, 'w');
    assert(file >= 0);
    cleanup = onCleanup(@() fclose(file));
    fprintf(file, '%s\n', text);
end

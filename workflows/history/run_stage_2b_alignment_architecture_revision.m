        fullfile(root, 'architecture_inventory.csv'));
    existingInventoryFile = fullfile(root, 'plot_inventory.csv');
    existingInventory = readtable(existingInventoryFile, 'TextType', 'string', ...
        'VariableNamingRule', 'preserve', 'Delimiter', ',');
